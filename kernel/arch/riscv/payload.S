/*
 * payload.S - Embed RAM Disk Image as Kernel Data (Phase 5)
 * 
 * OVERVIEW:
 * This file uses the '.incbin' assembler directive to include a single RAM
 * disk image (ramdisk.img) as raw bytes within the kernel image. The kernel
 * no longer depends on individual ELF symbols and instead treats the embedded
 * image as a generic storage blob.
 *
 * PHASE 5 MECHANISM - RAMDISK IMAGE:
 * The kernel only knows that _ramdisk_start points to a contiguous disk image.
 * It does not assume which programs exist or how many there are; that metadata
 * lives inside the image and is parsed by the RAMDISK layer.
 *
 * LINKING PROCESS:
 * Makefile rule: arch/riscv/payload.o depends on ramdisk.img
 *   - The image is generated by a RAMDISK tool (outside this file)
 *   - payload.S embeds the whole image with a single .incbin
 *   - Kernel exports _ramdisk_start/_ramdisk_end to access raw image bytes
 *
 * KERNEL ACCESS:
 *   extern uint8_t _ramdisk_start[];
 *   extern uint8_t _ramdisk_end[];
 *   size_t size = _ramdisk_end - _ramdisk_start;
 *
 * ADVANTAGES:
 *   - Decouples kernel from specific programs (no tight coupling)
 *   - Supports dynamic program discovery inside the image
 *   - Rebuilds only when the disk image changes
 *
 * NOTE:
 * This file only embeds the image. The RAMDISK parser/loader determines how
 * to locate and load ELF files from _ramdisk_start at runtime.
 */

/* Place in .rodata (read-only data section) */
.section .rodata

/* Export these symbols globally so kernel code can reference them */
.global _ramdisk_start
.global _ramdisk_end

/*
 * === ALIGNMENT ===
 * Align to 8-byte boundary for cleaner memory layout.
 * (Not strictly necessary for correctness, but improves cache/alignment)
 */
.balign 8

/*
 * === RAMDISK IMAGE START ===
 * Label marking where embedded ramdisk image begins.
 * The kernel treats this as a raw disk blob and parses it at runtime.
 */
_ramdisk_start:

    /*
    * === INCLUDE IMAGE ===
    * '.incbin' directive: assembler reads file and embeds as raw bytes.
    * File path relative to Makefile working directory.
    *
    * What gets embedded:
    *   ramdisk.img = packed image containing one or more ELF binaries
    *   - Image format is defined by the RAMDISK builder/parser
    *   - Kernel reads entries from _ramdisk_start at runtime
     */
    .incbin "ramdisk.img"
    
/*
 * === RAMDISK IMAGE END ===
 * Label marking where embedded ramdisk image ends.
 * Can be used to compute image size: _ramdisk_end - _ramdisk_start
 */
_ramdisk_end:
